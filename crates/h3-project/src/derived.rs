//! Files the Video Builder writes next to the session on every save. Port of the derived file code in
//! `builder/project.py` and `builder/audio.py`. The session stays the source of truth. These files let tools and the
//! Python Builder read the same project, for example `SceneNotes.json` is the fallback for an empty scene note.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use h3_core::pyval::{float_or_zero, round_half_even, text_or_empty};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};

use crate::atomic::{atomic_write_json, atomic_write_text};
use crate::layout::{context_folder, prompts_folder, scene_notes_path, srt_path};

const MINIMAX_INDEX: &str = "# MiniMax H3 project files\n\nGenerated by the Video Builder. The session JSON is the source of truth for MiniMax prompts and settings.\n\n## Primary MiniMax data\n\n- `vrgdg_builder_session.json` \u{2014} project `video_engine`, `minimax_h3_settings`, two/three-pass flags, and per-scene `minimax_h3_prompt`, mode, audio mode, references, continuity, stage outputs, and render history.\n- `subject_location/reference_descriptions.json` \u{2014} portable character and location names, IDs, and descriptions.\n- `subject_location/subject/<name>.txt` \u{2014} one character/subject description per file.\n- `subject_location/location/<name>.txt` \u{2014} one location description per file.\n\n## References and audio\n\n- `project_context/flux_references/subjects/` \u{2014} character reference images.\n- `project_context/flux_references/locations/` \u{2014} location reference images.\n- `project_context/flux_references/ingredients_sheets/` \u{2014} ingredient/reference sheets when used.\n- `project_audio/` \u{2014} project/global audio copied into the project.\n- `scene_audio/` \u{2014} scene audio assets, including MiniMax scene audio when applicable.\n- `scene_audio_trimmed/` \u{2014} trimmed scene-audio derivatives when created.\n\n## Rendered MiniMax outputs\n\n- `rendered_scene_videos/video_####-audio.mp4` \u{2014} final per-scene clips.\n- `rendered_scene_videos_backup/scene_####/` \u{2014} replaced/backed-up scene clips.\n- `scene_video_thumbnails/` \u{2014} rendered clip thumbnails.\n- `render_logs/` \u{2014} MiniMax render progress and diagnostics.\n\n## Not MiniMax-specific\n\n- `prompts/t2i_prompts.txt` \u{2014} image-generation prompts.\n- `prompts/i2v_prompts.txt` \u{2014} LTX image-to-video prompts; MiniMax prompts are in the session JSON.\n- `builder_segments.srt`, `SceneNotes.json`, and other shared context files.\n";

fn float_of(segment: &serde_json::Map<String, Value>, key: &str) -> f64 {
    float_or_zero(segment.get(key)).unwrap_or(0.0)
}

/// `HH:MM:SS,mmm`.
pub fn format_srt_time(seconds: f64) -> String {
    let total_ms = round_half_even(seconds * 1000.0).max(0);
    let (hours, rest) = (total_ms / 3_600_000, total_ms % 3_600_000);
    let (minutes, rest) = (rest / 60_000, rest % 60_000);
    format!("{hours:02}:{minutes:02}:{:02},{:03}", rest / 1000, rest % 1000)
}

/// Segments sorted by start. Entries that are not objects are skipped.
fn sorted_by_start(segments: &[Value]) -> Vec<&serde_json::Map<String, Value>> {
    let mut list: Vec<&serde_json::Map<String, Value>> = segments.iter().filter_map(Value::as_object).collect();
    list.sort_by(|a, b| float_of(a, "start").total_cmp(&float_of(b, "start")));
    list
}

/// The SRT text of the scene list, one cue per scene.
pub fn segments_to_srt(segments: &[Value]) -> String {
    let mut lines: Vec<String> = Vec::new();
    for (i, segment) in sorted_by_start(segments).into_iter().enumerate() {
        let index = i + 1;
        let start = float_of(segment, "start");
        let end = match segment.get("end") {
            Some(v) if h3_core::pyval::truthy(v) => float_or_zero(Some(v)).unwrap_or(start + 4.0),
            _ => start + 4.0,
        }
        .max(start + 0.1);
        let pick = ["label", "label", "t2i_prompt"].iter().filter_map(|k| segment.get(*k)).find(|v| h3_core::pyval::truthy(v));
        let text = match pick {
            Some(v) => text_or_empty(Some(v)).trim().to_string(),
            None => format!("Scene {index}"),
        };
        lines.extend([index.to_string(), format!("{} --> {}", format_srt_time(start), format_srt_time(end)), text, String::new()]);
    }
    format!("{}\n", lines.join("\n").trim())
}

/// `SceneNotes.json`: `SceneNote<N>` to the scene's timeline note.
pub fn write_scene_notes(project: &Path, segments: &[Value]) -> io::Result<PathBuf> {
    let mut notes = serde_json::Map::new();
    for (i, segment) in segments.iter().enumerate() {
        if let Some(segment) = segment.as_object() {
            notes.insert(format!("SceneNote{}", i + 1), json!(text_or_empty(segment.get("timeline_note"))));
        }
    }
    let path = scene_notes_path(project);
    atomic_write_json(&path, &Value::Object(notes))?;
    Ok(path)
}

/// Notes from `SceneNotes.json` by 1-based scene number, used when a scene's own note is empty.
pub fn load_scene_notes(project: &Path) -> std::collections::BTreeMap<u32, String> {
    let mut notes = std::collections::BTreeMap::new();
    let Ok(text) = fs::read_to_string(scene_notes_path(project)) else { return notes };
    let Some(Value::Object(data)) = crate::pyjson::parse(&text).ok() else { return notes };
    for (key, value) in data {
        let digits: String = key.chars().skip_while(|c| !c.is_ascii_digit()).take_while(char::is_ascii_digit).collect();
        if let Ok(number) = digits.parse() {
            notes.insert(number, text_or_empty(Some(&value)).trim().to_string());
        }
    }
    notes
}

/// `prompts/t2i_prompts.txt` and `prompts/i2v_prompts.txt`, scenes and overlay scenes by start time.
pub fn write_prompt_files(project: &Path, segments: &[Value], overlay: &[Value]) -> io::Result<()> {
    let all: Vec<Value> = segments.iter().chain(overlay.iter()).cloned().collect();
    let mut t2i: Vec<String> = Vec::new();
    let mut i2v: Vec<String> = Vec::new();
    for segment in sorted_by_start(&all) {
        let clean = |key: &str| text_or_empty(segment.get(key)).trim().to_string();
        if !clean("t2i_prompt").is_empty() {
            t2i.push(clean("t2i_prompt"));
        }
        if !clean("i2v_prompt").is_empty() {
            i2v.push(clean("i2v_prompt"));
        }
    }
    let join = |lines: &[String]| format!("{}{}", lines.join("\n\n").trim(), if lines.is_empty() { "" } else { "\n" });
    atomic_write_text(&prompts_folder(project).join("t2i_prompts.txt"), &join(&t2i))?;
    atomic_write_text(&prompts_folder(project).join("i2v_prompts.txt"), &join(&i2v))
}

/// The user's complete source lyrics, never rebuilt from the timeline.
pub fn save_full_lyrics(project: &Path, lyrics: Option<&Value>) -> io::Result<Option<PathBuf>> {
    let text = text_or_empty(lyrics).trim().to_string();
    if text.is_empty() {
        return Ok(None);
    }
    let path = context_folder(project).join("full_lyrics.txt");
    atomic_write_text(&path, &format!("{text}\n"))?;
    Ok(Some(path))
}

/// `[^A-Za-z0-9_. -]+` becomes `_`, then `" ._"` is trimmed from both ends.
pub fn safe_project_name(value: &str) -> String {
    let mut out = String::new();
    let mut in_run = false;
    for c in value.trim().chars() {
        if c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | ' ' | '-') {
            out.push(c);
            in_run = false;
        } else if !in_run {
            out.push('_');
            in_run = true;
        }
    }
    let trimmed = out.trim_matches([' ', '.', '_']).to_string();
    if trimmed.is_empty() { "VRGDG_MusicVideoBuilder".to_string() } else { trimmed }
}

/// Reference Builder descriptions as portable files: one text file per subject and location plus a lossless manifest.
pub fn save_reference_descriptions(project: &Path, refs: &Value) -> io::Result<Option<PathBuf>> {
    let Some(refs) = refs.as_object() else { return Ok(None) };
    let root = project.join("subject_location");
    let subject_dir = root.join("subject");
    let location_dir = root.join("location");
    fs::create_dir_all(&subject_dir)?;
    fs::create_dir_all(&location_dir)?;
    let mut manifest = refs.clone();
    for key in ["subjects", "locations"] {
        manifest.entry(key.to_string()).or_insert_with(|| json!([]));
    }
    for (key, folder, singular) in [("subjects", &subject_dir, "Subject"), ("locations", &location_dir, "Location")] {
        let items = refs.get(key).and_then(Value::as_array).cloned().unwrap_or_default();
        // Reserve space for the extension and the temporary sibling file of the atomic write.
        let folder_len = folder.display().to_string().chars().count() as i64;
        let max_stem = 16.max(120.min(240 - folder_len - 19)) as usize;
        for (i, item) in items.iter().enumerate() {
            let Some(item) = item.as_object() else { continue };
            let name = match item.get("name") {
                Some(v) if h3_core::pyval::truthy(v) => text_or_empty(Some(v)).trim().to_string(),
                _ => format!("{singular} {}", i + 1),
            };
            let description = text_or_empty(item.get("description")).trim().to_string();
            let mut stem = safe_project_name(&name);
            if stem.chars().count() > max_stem {
                let digest: String = Sha256::digest(name.as_bytes()).iter().map(|b| format!("{b:02x}")).collect();
                let head: String = stem.chars().take(max_stem - 11).collect();
                stem = format!("{}_{}", head.trim_end_matches([' ', '.', '_']), &digest[..10]);
            }
            let body = if description.is_empty() { String::new() } else { format!("{description}\n") };
            atomic_write_text(&folder.join(format!("{stem}.txt")), &body)?;
        }
    }
    let path = root.join("reference_descriptions.json");
    atomic_write_json(&path, &Value::Object(manifest))?;
    Ok(Some(path))
}

/// `MINIMAX_PROJECT_FILES.md` for MiniMax H3 projects.
pub fn write_minimax_index(project: &Path, session: &serde_json::Map<String, Value>) -> io::Result<Option<PathBuf>> {
    if text_or_empty(session.get("video_engine")).trim().to_lowercase() != "minimax_h3" {
        return Ok(None);
    }
    let path = project.join("MINIMAX_PROJECT_FILES.md");
    atomic_write_text(&path, MINIMAX_INDEX)?;
    Ok(Some(path))
}

pub fn srt_file(project: &Path) -> PathBuf {
    srt_path(project)
}
